'use client';

import * as React from 'react';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import {
  CreateWorkspaceSchema,
  CurrencyCode,
  WorkspaceRole,
} from '@uacm/shared-types';
import { useWorkspace } from '../providers/workspace-provider';
import { Button } from '../ui/button';
import { Input } from '../ui/input';
import { Label } from '../ui/label';

export const CreateWorkspaceFormSchema = CreateWorkspaceSchema.extend({
  slug: z.preprocess(
    (val) => (typeof val === 'string' && val.trim() === '' ? undefined : val),
    z
      .string()
      .min(2, 'Slug must be at least 2 characters')
      .max(100, 'Slug cannot exceed 100 characters')
      .regex(
        /^[a-z0-9-]+$/,
        'Slug must contain only lowercase alphanumeric characters and hyphens',
      )
      .optional(),
  ),
});

export type CreateWorkspaceFormInput = z.input<
  typeof CreateWorkspaceFormSchema
>;
export type CreateWorkspaceFormOutput = z.output<
  typeof CreateWorkspaceFormSchema
>;

export interface CreateWorkspaceFormProps {
  onSuccess?: () => void;
  onCancel?: () => void;
}

export function CreateWorkspaceForm({
  onSuccess,
  onCancel,
}: CreateWorkspaceFormProps) {
  const { addWorkspace } = useWorkspace();
  const [isSubmitting, setIsSubmitting] = React.useState(false);

  const {
    register,
    handleSubmit,
    watch,
    setValue,
    formState: { errors },
  } = useForm<CreateWorkspaceFormInput, unknown, CreateWorkspaceFormOutput>({
    resolver: zodResolver(CreateWorkspaceFormSchema),
    defaultValues: {
      name: '',
      slug: '',
      baseCurrency: CurrencyCode.USD,
    },
  });

  const selectedCurrency = watch('baseCurrency') || CurrencyCode.USD;
  const nameValue = watch('name') || '';
  const autoGeneratedPlaceholder = nameValue
    ? nameValue
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)/g, '') || 'e.g. growth-marketing-hq'
    : 'e.g. growth-marketing-hq';

  const onSubmit = async (data: CreateWorkspaceFormOutput) => {
    setIsSubmitting(true);
    try {
      const generatedSlug =
        (data.slug && data.slug.trim() !== '' ? data.slug : undefined) ||
        data.name
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, '-')
          .replace(/(^-|-$)/g, '');

      const newWorkspace = {
        id: `ws-${Date.now()}`,
        name: data.name,
        slug: generatedSlug,
        baseCurrency: data.baseCurrency,
        role: WorkspaceRole.OWNER,
      };

      addWorkspace(newWorkspace);
      onSuccess?.();
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <form
      onSubmit={handleSubmit(onSubmit)}
      className="space-y-4"
      data-testid="create-workspace-form"
    >
      {/* Workspace Name */}
      <div className="space-y-1 text-start">
        <Label htmlFor="workspace-name">Workspace Name *</Label>
        <Input
          id="workspace-name"
          placeholder="e.g. Growth Marketing HQ"
          {...register('name')}
          aria-invalid={!!errors.name}
        />
        {errors.name && (
          <p className="text-xs text-destructive">{errors.name.message}</p>
        )}
      </div>

      {/* Slug */}
      <div className="space-y-1 text-start">
        <Label htmlFor="workspace-slug">Slug (Identifier)</Label>
        <Input
          id="workspace-slug"
          placeholder={autoGeneratedPlaceholder}
          {...register('slug')}
          aria-invalid={!!errors.slug}
        />
        {errors.slug && (
          <p className="text-xs text-destructive">{errors.slug.message}</p>
        )}
        <p className="text-[11px] text-muted-foreground">
          Leave blank to auto-generate from workspace name, or use lowercase
          alphanumeric characters and hyphens.
        </p>
      </div>

      {/* Base Currency */}
      <div className="space-y-1 text-start">
        <Label htmlFor="workspace-currency">Base Currency *</Label>
        <select
          id="workspace-currency"
          value={selectedCurrency}
          onChange={(e) =>
            setValue('baseCurrency', e.target.value as CurrencyCode)
          }
          className="flex h-9 w-full rounded-md border border-input bg-transparent px-3 py-1 text-sm shadow-sm transition-colors focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-ring"
        >
          {Object.values(CurrencyCode).map((code) => (
            <option
              key={code}
              value={code}
              className="bg-background text-foreground"
            >
              {code}
            </option>
          ))}
        </select>
        {errors.baseCurrency && (
          <p className="text-xs text-destructive">
            {errors.baseCurrency.message}
          </p>
        )}
      </div>

      {/* Action Buttons */}
      <div className="flex justify-end gap-2 pt-2">
        {onCancel && (
          <Button type="button" variant="outline" onClick={onCancel}>
            Cancel
          </Button>
        )}
        <Button type="submit" disabled={isSubmitting}>
          {isSubmitting ? 'Creating...' : 'Create Workspace'}
        </Button>
      </div>
    </form>
  );
}
